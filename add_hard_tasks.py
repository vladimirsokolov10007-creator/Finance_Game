def opt(oid, text, mood, satiety, explanation, correct):
    return collections.OrderedDict([
        ("id", oid), ("text", text),
        ("effect", collections.OrderedDict([("mood", mood), ("satiety", satiety)])),
        ("explanation", explanation), ("correct", correct),
    ])


def step(num, text, options):
    return collections.OrderedDict([("step", num), ("text", text), ("options", options)])


def task(tid, topic, title, story, steps, reward):
    return collections.OrderedDict([
        ("id", tid), ("topic", topic), ("title", title), ("ageGroup", 1),
        ("story", story), ("scenario", steps), ("reward", reward),
    ])


